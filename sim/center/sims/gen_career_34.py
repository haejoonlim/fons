            if l2id == 'l2_spirit_knight':
                entry['spiritRoll'] = {'pool': list(SPIRITS), 'kind': 'weightedPick',
                                       'weights': [SPIRIT_WEIGHTS[s] for s in SPIRITS]}

            for (ksuf, kname, ktier, kdesc) in kws:
                kid = f'kw_{l2id[3:]}_{ksuf}'
                if l2id in NO_AXIS_TERMINAL:
                    kw = {'id': kid, 'name': kname, 'parentId': l2id, 'tier': ktier,
                          'power': powers.get(kid, DEFAULT_POWER),
                          'statMod': [DEFAULT_POWER] * NSTATS, 'desc': kdesc,
                          'nameRule': 'fixed'}
                    if l2id == 'l2_sage':
                        kw['intellectFloor'] = 130
                else:
                    kshape = LEXICON[kname]
                    p = powers.get(kid, DEFAULT_POWER)
                    kw = {'id': kid, 'name': kname, 'parentId': l2id, 'tier': ktier,
                          'power': p, 'statMod': stat_mod(kshape, p),
                          'desc': kdesc, 'shape': kshape}
                entry['keywords'].append(kw)

            # 종점 카드 — 원소 마도사 7장 · 정령기사 7장
            if l2id in ('l2_elementalist', 'l2_spirit_knight'):
                for (el, kname, ktier, kdesc, kshape, rule) in elemental_cards(l2id):
                    kid = f'kw_{l2id[3:]}_{el or "great"}'
