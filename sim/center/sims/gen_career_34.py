            # 원소 + 마도사 (사용자 지시 2026-09-29 — '대' 는 대원소마도사만)
            name = f'{ELEMENT_SUFFIX[el]}마도사'         # 화염마도사 · 물마도사 …
            rule = 'firstElement'
