def shape_axes(shape):
    """shape 가 대표하는 축 인덱스 — SHAPE 벡터의 **1위**(34차 전 축 단독 1위다).

    33차까지는 '상위 2위 안' 을 검사했다. 공동 2위 축(방어=HP·DEF 등) 때문에
    그렇게 했는데, 34차는 **13축 전부 대표 스탯이 단독 1위**다.
    → '1위 == 대표 스탯' 으로 검사하면 훨씬 엄격하고 오탐이 없다.
    아래 shape_stat() 가 이 단독성을 HARD 로 보장한다.
    """
    v = SHAPE[shape]
    return {max(range(len(v)), key=lambda i: (v[i], -i))}


def top_axes(values, n):
    order = sorted(range(len(values)), key=lambda i: -values[i])
    cut = values[order[n - 1]]
    return set(i for i in range(len(values)) if values[i] >= cut - 1e-9)


def validate(jobs):
    err = []
    l1 = [j for j in jobs if j['stage'] == 1]
    l2 = [j for j in jobs if j['stage'] == 2]
    l3 = [j for j in jobs if j['stage'] == 3]   # 35차 — 생활직
    names = set()
    nk = 0
    tier = defaultdict(int)

    # ── R1~R5 이름 ──
    for j in jobs:
        if j['name'] in names:
            err.append(f"이름 중복: {j['name']}")
        names.add(j['name'])
        for w in TITLE_WORDS:
            # 35차 — L3 생활직은 직함어가 아니라 **적성 이름**이라 검사하지 않는다
            # (대장장이는 적성 13종 중 하나 · 05 §6 '대장' 개명)
            if j['name'].endswith(w) and j['stage'] in (1, 2):
                err.append(f"R1 직함어 금지: {j['name']}")
        if j['name'] in RETIRED_NAMES and j['name'] not in KEEP_NAMES:
            err.append(f"R1 죽은 이름 재사용: {j['name']}")

    nk = sum(len(j.get('keywords') or []) for j in l2 + l3)   # 35차 — L3(L4 13장) 포함

    # ── R11 ★ 36차 — 시작부터 L2 로 확정되는 L1 규칙이 트리와 **실제로 맞나** ──
    #   합계만 맞아서는 부족하다 — startL2 에 적힌 L2 가 없거나, parentId 가 다른 L1 을
    #   가리키면 규칙이 조용히 죽는다. (지금까지 세 번 날아간 "합은 맞는데 내용이 틀린다")
    by_id = {j['id']: j for j in jobs}
    l2_ids = {j['id'] for j in l2}
    for lid, spec in START_AS_L2.items():
        if lid not in by_id:
            err.append(f"R11 시작-L2 L1 이 트리에 없음: {lid}")
            continue
        for sid in spec['startL2']:
            if sid not in l2_ids:
                err.append(f"R11 startL2 가 L2 가 아님: {lid} → {sid}")
            elif by_id[sid]['parentId'] != lid:
                err.append(f"R11 startL2 의 parentId 불일치: {sid} 의 부모는 "
                           f"{by_id[sid]['parentId']} 이나 규칙은 {lid}")
        if spec['entryStage'] != 2:
            err.append(f"R11 entryStage 는 2 여야 함: {lid} = {spec['entryStage']}")
    # 이 규칙이 없으면 안 되는 L1 — 마법/종교 계열이 '스킬로 전직해야 쓸 수 있다' 가 된다
    for need in ('l1_mage', 'l1_supporter'):
        if need not in START_AS_L2:
            err.append(f"R11 {need} 는 시작부터 L2 확정이어야 함")

    # ── R1 키워드 이름 전역 중복 0 (직업명과 겹쳐도 안 된다) ──
    #   30차부터 있던 규칙인데 34차 초안에서 안 돌아서 정령기사 7장이 전부
    #   '정령기사' 로 겹쳤다. C# ProgressionData.Validate 가 같은 규칙을
    #   HARD 로 검사하므로 여기서도 걸어야 한다.
    for j in jobs:
        for k in j.get('keywords') or []:
            if k['name'] in names:
                err.append(f"R1 키워드 이름 중복: {k['name']} ({j['name']} · {k['id']})")
            names.add(k['name'])

    # ── R6 사전 매칭 (고아 항목도 실패) ──
    for k, sh in LEXICON.items():
        if sh not in SHAPE:
            err.append(f"R6 사전이 미등록 축을 가리킴: {k} → {sh}")
    used = set()
    for j in l2 + l3:
        for k in j.get('keywords') or []:
            if k.get('nameRule') in ('fixed', 'spirit', 'firstElement'):
                continue          # 이름이 런타임에 정해지는 카드는 사전 매칭 대상이 아니다
            if k.get('name') not in LEXICON:
                err.append(f"R6 사전에 없는 키워드: {k['name']}")
            used.add(k.get('name'))
    for k in LEXICON:
        if k not in used:
            err.append(f"R6 고아 항목(아무도 안 가리킴): {k}")

    # ── R7 문장 (35차 — L2 키워드 + L3 생활직의 L4 키워드) ──
    for j in l2 + l3:
        for k in j.get('keywords') or []:
            if k['name'] in k['desc']:
                err.append(f"R7 자기참조: {k['name']} → {k['desc']}")
            for w in RETIRED_NAMES:
                if w in k['desc']:
                    err.append(f"R7 죽은 이름 참조: {k['name']} → {k['desc']}")
            if k.get('nameRule') == 'spirit':
                continue          # 종점 카드는 이름이 L2 이름이므로 자기참조가 정상
            if k['desc'].count('.') > 2:
                err.append(f"R7 3문장 초과: {k['name']}")
            if not k['desc'].endswith(ENDING_OK):
                err.append(f"R8 관형 미탈락: {k['name']} → {k['desc']}")
    for f, cap in REPEAT_FRAMES.items():
        n = sum(1 for j in l2 + l3 for k in j.get('keywords') or [] if f in k['desc'])
        if n > cap:
            err.append(f"R7 반복 프레임 초과: '{f}' {n}건 > {cap}")

    # ── R8 티어 형식 (1/2/3 · 1이 가장 어려움) ──
    for j in l2 + l3:
        for k in j.get('keywords') or []:
            if k['tier'] not in ('1', '2', '3'):
                err.append(f"R8 티어 형식: {k['name']} = {k['tier']}")
            tier[k['tier']] += 1

    # ── ★ 35차 R11 — 티어가 statMod 배율과 **같은 방향**이어야 한다 ──
    #   statMod 가 실제로 영웅 스탯에 곱해진 뒤 드러난 문제: 티어 1 이 43장으로 과다하고
    #   최대축 배율은 티어 1(×1.466) > 티어 3(×1.370) 으로 **역전**이었다.
    #   "가장 어려운 카드" 가 실제로 가장 강해야 읽힌다 — 이게 뒤집히면 3장 중
    #   무엇을 고르는지 판단할 근거가 사라진다.
    peak = {t: [] for t in ('1', '2', '3')}
    for j in l2 + l3:
        for k in j.get('keywords') or []:
            peak[k['tier']].append(max(k['statMod']))
    avg = {t: (sum(v) / len(v) if v else 0.0) for t, v in peak.items()}
    if not (avg['1'] >= avg['2'] >= avg['3']):
        err.append(f"R11 티어↔배율 역전: 티어별 최대축 배율 "
                   f"1={avg['1']:.4f} 2={avg['2']:.4f} 3={avg['3']:.4f} — "
                   f"1 ≥ 2 ≥ 3 이어야 한다 (retier.reassign 누락?)")
    # 전역 3:6:4 (±12%p). 30차부터 손으로 쓰인 티어는 43:38:13 으로 1 이 터져 있었다.
    tot = sum(tier.values()) or 1
    for t, lo, hi in (('1', 15, 38), ('2', 30, 55), ('3', 15, 40)):
        pct = tier[t] * 100 / tot
        if not (lo <= pct <= hi):
            err.append(f"R11 티어{t} 비중 {pct:.1f}% 가 허용 범위 {lo}~{hi}% 밖")

    # ── R9 준비 — 축 벡터의 대표 스탯은 단독 1위여야 한다 ──
    for sh, v in SHAPE.items():
        order = sorted(range(len(v)), key=lambda i: -v[i])
        if v[order[0]] - v[order[1]] <= 1e-9:
            err.append(f"R9 축 '{sh}' 의 대표 스탯이 공동 1위다 "
                       f"({AX_NAME[order[0]]}={v[order[0]]} = {AX_NAME[order[1]]}) — "
                       f"'1위 == 대표' 검사를 쓸 수 없다")

    # ── R9 축 ↔ 배율 정합 ──
    for j in l2 + l3:
        for k in j.get('keywords') or []:
            sh = k.get('shape')
            if not sh:
                continue
            want = shape_axes(sh)
            v = [float(x) for x in k['statMod']]
            top = max(range(len(v)), key=lambda i: (v[i], -i))
            if top not in want:
                err.append(f"R9 {k['name']} 축 '{sh}' 의 대표는 {AX_NAME[next(iter(want))]} 인데 "
                           f"statMod 1위는 {AX_NAME[top]}({v[top]:.4f}) — {k['id']}")
            if min(k['statMod']) <= 0:
                err.append(f"R10 statMod 에 0 이하: {k['id']}")

    # ── R10 statMod 14축 일관성 ──
    for j in l2 + l3:
        for k in j.get('keywords') or []:
            if len(k['statMod']) != NSTATS:
                err.append(f"R10 statMod 길이 {len(k['statMod'])} ≠ {NSTATS}: {k['id']}")

    # ── L1 role 동질성 (무명자=무직 예외) ──
    for a in l1:
        kids = [b for b in l2 if b['parentId'] == a['id']]
        if a['id'] == 'l1_nameless':
            continue
        for b in kids:
            if b['role'] != a['role']:
                err.append(f"L1 role 동질성 위반: {a['name']}({a['role']}) → {b['name']}({b['role']})")

    # ── 종점 키워드 개수 (35차 — 무직 0 은 L2 종점이 아니라 L3 의 부모다) ──
    EXPECT = {'l2_spirit_knight': 7, 'l2_elementalist': 7, 'l2_jobless': 0, 'l2_sage': 1}
    for j in l2:
        n = len(j.get('keywords') or [])
        want = EXPECT.get(j['id'], 3)
        if n != want:
            err.append(f"종점 규칙: {j['name']} 키워드 {n}개 (기대 {want})")

    # ── 35차 L3 생활직 검증 (L3 은 1종 · L4 는 13장) ──
    if len(l3) != 1:
        err.append(f"L3 이 {len(l3)}개다 — 생활직은 하나여야 한다 (35차 사용자 결정)")
    for j in l3:
        if j['id'] != L3_ID or j['name'] != L3_NAME:
            err.append(f"L3 이 {j['id']}·{j['name']} 이다 (기대 {L3_ID}·{L3_NAME})")
        if j.get('parentId') != L3_PARENT:
            err.append(f"L3 의 부모가 {L3_PARENT} 가 아니다")
        if j.get('role') != '생활':
            err.append(f"L3 의 role 이 '생활' 이 아니다")
        if j.get('lawTags'):
            err.append("L3 에 lawTags 가 있다 — 생활직은 원소를 법칙으로 갖지 않는다")
        kws = j.get('keywords') or []
        if len(kws) != len(APT_NAMES):
            err.append(f"L4 키워드가 {len(kws)}개다 (기대 {len(APT_NAMES)} = 적성 13종)")
        # L4 13장 이름이 적성 13종과 1:1
        l4_names = [k['name'] for k in kws]
        if l4_names != list(APT_NAMES):
            err.append(f"L4 이름이 적성 13종과 1:1 이 아니다: {set(l4_names) ^ set(APT_NAMES)}")
        for k in kws:
            if k.get('domain') not in APT_DOMAINS:
                err.append(f"L4 {k['name']} 의 domain '{k.get('domain')}' 가 미등록")

    # ── 무(空) 규칙 ──
    for j in jobs:
        if j['id'] == 'l2_elementalist':
            if 'void' in j['lawTags']:
                err.append("원소 마도사 법칙에 무가 있다 (마나가 무 그 자체이므로 없어야 한다)")
            for k in j.get('keywords') or []:
                if '무' in k['name']:
                    err.append(f"대원소마도사 카드에 무가 있다: {k['name']}")
        if j['id'] == 'l2_sage':
            if j['lawTags'] != ['void']:
                err.append(f"현자 법칙은 무만이어야 한다: {j['lawTags']}")
        if j['id'] == 'l2_spirit_knight':
            sr = j.get('spiritRoll')
            if not sr or len(sr['pool']) != 7 or len(sr['weights']) != 7:
                err.append("정령기사 spiritRoll 형식 오류")
            elif not sr['weights'][6] < min(sr['weights'][:6]):
                err.append("무(空) 가중치가 나머지보다 작아야 한다")

    # ── 대현자 지능 130 ──
    gs = [k for j in l2 for k in j.get('keywords') or [] if k['id'] == 'kw_sage_greatsage']
    if not gs or gs[0].get('intellectFloor') != 130:
        err.append("대현자에 intellectFloor=130 이 없다")

    # ── 축 13종 전부 사용 (고아 축) ──
    used_shapes = {k.get('shape') for j in l2 + l3 for k in j.get('keywords') or []} - {None}
    for sh in SHAPE:
        if sh not in used_shapes:
            err.append(f"고아 축(아무 키워드도 안 씀): {sh}")
    for sh in used_shapes:
        if sh not in SHAPE:
            err.append(f"미등록 축: {sh}")

    return err, (len(l1), len(l2), len(l3), nk, len(jobs),
                 dict(sorted(tier.items())), used_shapes)


def main():
    jobs = build()
    err, (l1c, l2c, l3c, nk, total, tier, shapes) = validate(jobs)
    n_l2_kw = nk - l3c * len(APT_NAMES)   # L3 은 1종 · L4 = 적성 13종
    n_l4 = l3c * len(APT_NAMES)
    print(f"L1 {l1c} · L2 {l2c} · L3 생활직 {l3c} · 키워드 {nk} (L2 {n_l2_kw} + L4 {n_l4}) "
          f"= 나무 {total} · 티어 {tier}")
    print(f"축 {len(SHAPE)}종 (스탯 {NSTATS}종): {' '.join(sorted(shapes))}")
    if err:
        print(f"FAIL ({len(err)}건):")
        for e in err[:40]:
            print('  -', e)
        return 1
    print(f"OK — R1~R10 0 위반 · 종점 3곳(현자 1 · 정령기사 7 · 원소마도사 7) · "
          f"무직 › 생활직 1종 › L4 {n_l4}장(적성 13종) · 무 규칙 통과")
    if '--dry' in sys.argv:
        return 0
    root = {'$schema': 'job_tree/v3.4', 'version': '3.4.0',
            'l1Count': l1c, 'l2Count': l2c, 'l3Count': l3c, 'keywordCount': nk,
            # ★ 36차 — L1 2개(마법사·지원가)는 stage=1 이나 실제로는 L2 로 시작한다.
            #   ★ 2026-09-30 — 그냥 L1 id 목록만 남기면 **규칙이 유실된다**. C# 이 읽을 수 있도록
            #   entryStage·rule·startL2·needTags 를 그대로 실어 보낸다(원본 START_AS_L2 가 진실원).
            #   이래야 `CareerPromotionEngine.CandidatesOf` 가 후보를 이 목록으로 제한할 수 있다.
            'startAsL2': [dict({'l1Id': k}, **v) for k, v in sorted(START_AS_L2.items())],
            'jobs': jobs}
    with open(OUT, 'w', encoding='utf-8') as fh:
        json.dump(root, fh, ensure_ascii=False, indent=1)
    print(f"OK — wrote {os.path.relpath(OUT, ROOT)}")
    return 0


