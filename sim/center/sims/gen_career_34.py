                 '마귀',   # 51차 — 사람에게 안전하지 않다 (공격성 0.6~0.7) → 마물로 교체
                 '견습', '숙련', '장인',   # 49차 — 길눈·길꾼·길지기로 교체 (일반 계급어는 안 쓴다)
