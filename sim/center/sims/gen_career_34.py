def stat_mod(shape, power):
    """SHAPE 벡터 → statMod 13축.

    30차 계약: statMod 는 **재배분**이다 — 총량은 power 가 담당하고 방향만 옮긴다.
    그런데 38차 실측에서 방향마다 CP 상승률이 ×0.98~×1.22 로 벌어졌다. 원인은
    중심을 **비가중 평균**으로 잡았기 때문 — 공격력(+2.0)을 올리는 카드와
    스태미너(+0.03)를 올리는 카드가 CP 로 다른 값이 됐다.
    → 중심을 **CP 가중 평균**으로 잡는다. 그러면 가중 CP 증가량이 항상 0 이 되어
      카드 한 장의 CP 배율 == power 가 **구조적으로** 성립한다.
    """
    v = SHAPE[shape]
    w = [CP_W[c] * REF_BASE[i] for i, c in enumerate(AX_NAME)]
    mw = sum(wi * vi for wi, vi in zip(w, v)) / sum(w)
    return [round(power * (1.0 + REALLOC * (x - mw)), 4) for x in v]


def elemental_cards(l2id):
    """원소 마도사 7장 · 정령기사 7장 — 원소/정령 이름이 앞쪽에 붙는다."""
    out = []
