                 '매듭', '해봉', '선도', '살핌', '우회',
                 '곡사',   # 44차 초안 — 지형·엄폐 판정이 필요해 같은 날 폐기
                 '수생', '걸기', '액운', '야영',   # 45차 — 같은 자리에서 다시 고른 이름
                 '조류', '포유', '답사', '인도',   # 46차 — 짐승·뱀·발자국·표식·이정표로 교체 ('개척' 은 52차에 되살림)
                 # 47차 — 계급어(견습·숙련·장인)로 교체. '표식' 은 넣지 않는다 —
                 #   낙인 설명의 "저주 표식" 같은 일반어와 같은 글자다 (용어집 동철 주의).
                 '발자국', '이정표',   # 47차
