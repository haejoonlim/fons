def _load_cp_weights():
    with open(os.path.join(ROOT, 'data', 'races.json'), encoding='utf-8') as fh:
        raw = json.load(fh)['meta'].get('cpWeights') or {}
    missing = [c for c in AX_NAME if c not in raw]
    if missing:
        raise SystemExit(f'races.json meta.cpWeights 누락: {missing}')
    return {c: float(raw[c]) for c in AX_NAME}


