def generate():
    """105종 생성 — {종족: {슬롯: (이름, 효과문, 가중치)}}"""
    out = {}
    for race in RACES:
        table = {}
        for i, slot in enumerate(SLOTS[:-1]):
            name = APT_NAMES[race][i]
            stat, val = SLOT_EFFECT[slot]
            table[slot] = (name, f'{stat} +{val}%/등급 (가안)', SLOT_W[slot])
        sig_name, sig_fmt, sig_val = SIGNATURE[race]
        sig_w = 10 if race in LEGACY_HOLDERS.get(sig_name, set()) else SLOT_W['시그니처']
        table['시그니처'] = (sig_name, sig_fmt.format(v=sig_val), sig_w)
        out[race] = table
    return out


def selfcheck(tables):
    errs = []
    names = [n for t in tables.values() for (n, _, _) in t.values()]
    if len(names) != 105:
        errs.append(f'총 개수 {len(names)} ≠ 105')
    if len(set(names)) != len(names):
        dupes = {n for n in names if names.count(n) > 1}
        # 숲의 언어·산맥의 뼈·무리의 본능은 그룹 승계라 의도적 중복
        intended = set(LEGACY_HOLDERS)
        dupes -= intended
        if dupes:
            errs.append(f'의도 밖 이름 중복: {dupes}')
    common = ['정교한 손끝', '일사불란', '암중적응', '거상의 수완', '상성의 통찰', '실전 감각']
    hit = set(names) & set(common)
    if hit:
        errs.append(f'공용 6종과 충돌: {hit}')
    legacy = [n for t in tables.values() for (n, _, _) in [t['시그니처']]]
    if len(set(legacy)) != 8:
        errs.append(f'기존 시그니처 8종 승계 실패: {sorted(set(legacy))}')
    if not (set(legacy) == set(LEGACY_HOLDERS)):
        errs.append('승계 이름 ↔ LEGACY_HOLDERS 불일치')
    return errs


